function normalizeRawAsset(assetName) {
  return String(assetName || '')
    .replace(/^(?:SM|SK)_(?:Wep|Prop|Item|Veh|Bld|Env)_/i, '')
    .replace(/_Static$/i, '')
    .replace(/_Preset_(\d+)/gi, ' Preset $1')
    .replace(/_Preset$/gi, '')
    .replaceAll('_', ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

export function makeFriendlyNameEn(pack, assetName) {
  const shortPack = String(pack || '').replace(/^Polygon_?/, '');
  const cleanAsset = String(assetName || '')
    .replace(/^(?:SM|SK)_(?:Wep|Prop|Item|Veh|Bld|Env)_/i, '')
    .replace(/_Static$/, '')
    .replace(/_Preset_/, ' ');
  return `${shortPack} · ${cleanAsset.replaceAll('_', ' ')}`;
}

export function makeFriendlyName(pack, assetName) {
  const shortPack = String(pack || '').replace(/^Polygon_?/, '');
  const packZh = PACK_ZH[shortPack] || shortPack;
  let body = normalizeRawAsset(assetName);

  // Clean trailing redundant markers like "01 03" or standalone "Preset"
  body = body.replace(/\s+Preset\b/gi, '');

  // Strip noise words like "Prop" at start
  body = body.replace(/^Prop\s+/i, '');

  // Apply multi-word phrase replacements (produces Chinese + preserved capture numbers)
  let work = body;
  for (const [re, rep] of PHRASE_RULES) {
    work = work.replace(re, rep);
  }

  // Split remaining tokens and translate word-by-word while keeping numbers & already-translated Chinese runs intact
  const rawTokens = work.split(/\s+/).filter(Boolean);
  const outParts = [];
  const trailingNums = [];

  for (let i = 0; i < rawTokens.length; i++) {
    const tok = rawTokens[i];
    // Pure digits or version tokens go cleanly at the end of the item name
    if (/^\d+$/.test(tok)) {
      trailingNums.push(tok);
      continue;
    }
    // Clean parenthetical tag or Chinese already produced by PHRASE_RULES
    if (/[\u4e00-\u9fff]/.test(tok)) {
      outParts.push(tok);
      continue;
    }
    if (Object.hasOwn(MOD_WORDS, tok)) {
      const m = MOD_WORDS[tok];
      if (m) outParts.push(m);
      continue;
    }
    if (Object.hasOwn(NOUN_WORDS, tok)) {
      outParts.push(NOUN_WORDS[tok]);
      continue;
    }
    // Keep legitimate short ASCII codes (SUV, A, B, etc.) or flag unknown
    if (/^(?:SUV|UFO|DJ|TV|DSLR|CRT|APC|POV|HE|RPG|SMG|SKG|A|B)$/i.test(tok)) {
      outParts.push(tok.toUpperCase());
      continue;
    }
    outParts.push(tok);
  }

  // Normalize redundant consecutive characters or parenthetical cleanups like "洁净版"
  let itemZh = outParts.join('').replace(/\s+/g, '');
  // Move (洁净版) / (满配) / (含粮) to after numbers or keep tidy before suffix
  const parenTags = [];
  itemZh = itemZh.replace(/（([^）]+)）|\(([^)]+)\)/g, (_m, g1, g2) => {
    parenTags.push(g1 || g2);
    return '';
  });

  // Pack-aware refinement where identical English noun means a very specific domain object
  if (shortPack === 'Adventure' || shortPack === 'FantasyKingdom') {
    if (itemZh === '圆桶') itemZh = '木桶';
    if (itemZh === '叠放圆桶') itemZh = '叠放木桶';
    if (itemZh === '陶罐' && /^0[23]$/.test(trailingNums[0] || '')) itemZh = '双耳陶罐';
  } else if (shortPack === 'Apocalypse' || shortPack === 'BattleRoyale' || shortPack === 'Military' || shortPack === 'War') {
    if (itemZh === '圆桶') itemZh = '铁油桶';
    if (itemZh === '叠放圆桶') itemZh = '叠放铁油桶';
  } else if (shortPack === 'SciFiSpace') {
    if (itemZh === '圆桶') itemZh = '能量储罐';
  } else if (shortPack === 'StreetRacer') {
    if (itemZh === '货箱') itemZh = '赛用木箱';
  } else if (shortPack === 'Casino') {
    if (itemZh === '警用') itemZh = '警用巡逻车';
  } else if (shortPack === 'Scifi') {
    if (itemZh === '经典') itemZh = '经典科幻跑车';
    if (itemZh === '复古') itemZh = '复古科幻跑车';
  }

  const numStr = trailingNums.length ? ` ${trailingNums.join('-')}` : '';
  const tagStr = parenTags.length ? `(${parenTags.join('·')})` : '';
  return `${itemZh}${numStr}${tagStr} · ${packZh}`;
}
