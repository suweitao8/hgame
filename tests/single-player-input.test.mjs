import test from 'node:test';
import assert from 'node:assert/strict';
import { createInputManager, defineInputContext, createSinglePlayerInput } from '../assets/runtime/platform/input.js';
import { createI18n } from '../assets/runtime/ui/i18n.js';

test('single-player device ownership, hot swap, disconnect and localized prompts', () => {
  const target = new EventTarget();
  const input = createInputManager({ target });
  const pad = { index: 0, id: 'Nintendo Switch', mapping: 'standard', buttons: [{ value: 0 }, { value: 0 }], axes: [0.1] };
  const pads = [pad];
  const disconnected = [];
  const controls = createSinglePlayerInput({ input, getGamepads: () => pads, onDisconnect: index => disconnected.push(index) });
  controls.router.pushContext(defineInputContext('menu', { actions: { Confirm: ['Enter', 'Pad0'], Cancel: ['Escape', 'Pad1'] } }));
  const i18n = createI18n({ locale: 'zh-CN', messages: { 'zh-CN': { help: '{Action:Confirm} 确认' }, en: { help: 'Confirm with {Action:Confirm}' } } });
  controls.update();
  assert.equal(controls.device, 'keyboard');
  pad.buttons[0].value = 1;
  controls.update();
  assert.equal(controls.router.wasPressed('Confirm'), true);
  assert.deepEqual(controls.promptParts(i18n, 'help', 'menu'), [{ action: 'Confirm', glyph: 'B' }, ' 确认']);
  pad.buttons[0].value = 0;
  controls.update();
  controls.setSwapConfirmCancel(true);
  pad.buttons[1].value = 1;
  controls.update();
  assert.equal(controls.router.wasPressed('Confirm'), true);
  i18n.setLocale('en');
  assert.deepEqual(controls.promptParts(i18n, 'help', 'menu'), ['Confirm with ', { action: 'Confirm', glyph: 'A' }]);
  pads.length = 0;
  controls.update();
  assert.equal(controls.router.wasReleased('Confirm'), true);
  assert.deepEqual(disconnected, [0]);
  target.dispatchEvent(Object.assign(new Event('keydown'), { code: 'Enter' }));
  controls.update();
  assert.equal(controls.router.wasPressed('Confirm'), true);
  controls.dispose();
  input.dispose();
});

test('a second controller takes over only on new input and idle drift leaves keyboard active', () => {
  const target = new EventTarget();
  const input = createInputManager({ target });
  const first = { index: 0, id: 'Xbox', mapping: 'standard', buttons: [{ value: 0 }], axes: [0.24, 0] };
  const second = { index: 1, id: 'DualSense', mapping: 'standard', buttons: [{ value: 0 }], axes: [0, 0] };
  const controls = createSinglePlayerInput({ input, getGamepads: () => [second, first] });
  controls.router.pushContext(defineInputContext('menu', { actions: { Confirm: ['Enter', 'Pad0'], Right: ['StickRight'] } }));
  controls.update();
  assert.equal(controls.device, 'keyboard');
  first.buttons[0].value = 1;
  controls.update();
  assert.equal(controls.gamepadIndex, 0);
  second.buttons[0].value = 1;
  controls.update();
  assert.equal(controls.gamepadIndex, 1);
  assert.equal(controls.getGlyph('menu', 'Confirm'), '×');
  target.dispatchEvent(Object.assign(new Event('keydown'), { code: 'KeyK' }));
  controls.update();
  assert.equal(controls.device, 'keyboard');
  assert.equal(controls.router.isDown('Confirm'), false);
  first.axes[0] = 0.26;
  controls.update();
  assert.equal(controls.gamepadIndex, 0);
  first.axes[0] = 0.23;
  controls.update();
  assert.equal(controls.router.isDown('Right'), true);
  first.axes[0] = 0.19;
  controls.update();
  assert.equal(controls.router.wasReleased('Right'), true);
  controls.dispose();
  input.dispose();
});
