function parseArgs(argv) {
  const opts = { specPath: null, demo: false, evalMode: false, scaffold: null, assetsFrom: null, allowDraft: false, json: false, help: false };
  for (let i = 0; i < argv.length; i++) {
    const token = argv[i];
    if (token === '--demo') opts.demo = true;
    else if (token === '--eval') opts.evalMode = true;
    else if (token === '--spec') opts.specPath = argv[++i];
    else if (token === '--scaffold') opts.scaffold = argv[++i];
    else if (token === '--assets-from') opts.assetsFrom = argv[++i];
    else if (token === '--allow-draft') opts.allowDraft = true;
    else if (token === '--json') opts.json = true;
    else if (token === '--help' || token === '-h') opts.help = true;
    else if (!token.startsWith('-') && !opts.specPath) opts.specPath = token;
    else throw new Error(`Unknown or incomplete argument: ${token}`);
  }
  if (!opts.help && !opts.demo && !opts.specPath) {
    throw new Error('Usage: node validate-spec.mjs <clean-spec.json> [--eval] [--scaffold <project-dir>] [--json] | --demo');
  }
  return opts;
}

function scanCompliance(node, keyPath, violations) {
  if (node === null || node === undefined) return;
  if (typeof node === 'string') {
    if (LOCAL_PATH_RE.test(node)) {
      violations.push(`${keyPath}: local disk path detected`);
    }
    if (BINARY_NAME_RE.test(node)) {
      violations.push(`${keyPath}: proprietary binary/archive filename detected`);
    }
    const lines = node.split(/\r?\n/);
    if (lines.length > 3 && /[;{}]|\b(?:public|private|class|struct|function|void|return)\b/.test(node)) {
      violations.push(`${keyPath}: multi-line source/decompiled snippet (>3 lines) detected`);
    }
    return;
  }
  if (Array.isArray(node)) {
    node.forEach((item, idx) => scanCompliance(item, `${keyPath}[${idx}]`, violations));
    return;
  }
  if (typeof node === 'object') {
    for (const [k, v] of Object.entries(node)) {
      if (LOCAL_PATH_RE.test(k) || BINARY_NAME_RE.test(k)) {
        violations.push(`${keyPath}.${k}: disallowed identifier`);
      }
      scanCompliance(v, `${keyPath}.${k}`, violations);
    }
  }
}

function isPosFinite(v) {
  return typeof v === 'number' && Number.isFinite(v) && v > 0;
}

function pickNum(...candidates) {
  for (const c of candidates) {
    if (typeof c === 'number' && Number.isFinite(c)) return c;
    if (c && typeof c === 'object' && typeof c.value === 'number' && Number.isFinite(c.value)) return c.value;
  }
  return null;
}

function scanUnknownOrNull(node, keyPath, out) {
  if (node === undefined) return;
  if (node === null) {
    out.push(`${keyPath}: value is null (未逆向参数必须显式标为 status: "hgame-fallback" 并填入推荐标准值)`);
    return;
  }
  if (typeof node === 'number') {
    if (!Number.isFinite(node)) {
      out.push(`${keyPath}: value is NaN/Infinity`);
    }
    return;
  }
  if (typeof node === 'string') {
    const trimmed = node.trim().toLowerCase();
    if (trimmed === 'unknown' || trimmed === 'nan' || trimmed === '') {
      out.push(`${keyPath}: contains "${node}" (禁止携带 unknown/NaN/空值进入生成阶段)`);
    }
    return;
  }
  if (Array.isArray(node)) {
    node.forEach((item, idx) => scanUnknownOrNull(item, `${keyPath}[${idx}]`, out));
    return;
  }
  if (typeof node === 'object') {
    for (const [k, v] of Object.entries(node)) {
      scanUnknownOrNull(v, `${keyPath}.${k}`, out);
    }
  }
}

function validateUnitSystem(spec) {
  const unitViolations = [];
  let unitScore = 0;

  if (spec.unitSystem === REQUIRED_UNIT_SYSTEM) {
    unitScore += 10;
  } else {
    unitViolations.push(`unitSystem must be "${REQUIRED_UNIT_SYSTEM}" (got ${JSON.stringify(spec.unitSystem ?? null)})`);
  }

  const conv = spec.unitConversions || spec.normalization || null;
  if (!conv || typeof conv !== 'object') {
    unitViolations.push('unitConversions missing: must declare distance & time conversion factors to SI meters/seconds');
  } else {
    const distScale = pickNum(
      conv.distance?.toMetersScale,
      conv.distance?.scale,
      conv.distanceScaleToMeters,
      conv.space?.toMetersScale,
    );
    const timeScale = pickNum(
      conv.time?.toSecondsScale,
      conv.time?.scale,
      conv.timeScaleToSeconds,
    );
    const tickHz = pickNum(conv.time?.tickHz, spec.engineRecipe?.tickHz);
    const hasDistance = isPosFinite(distScale);
    const hasTime = isPosFinite(timeScale) || isPosFinite(tickHz);
    if (!hasDistance) {
      unitViolations.push('unitConversions.distance.toMetersScale must be a positive finite number (e.g. 0.01905 for Hammer or px->m scale)');
    }
    if (!hasTime) {
      unitViolations.push('unitConversions.time must declare a positive toSecondsScale or tickHz');
    }
    if (hasDistance && hasTime) {
      unitScore += 10;
    }
  }

  return { unitViolations, unitScore };
}

function extractCoreAndTriangle(spec) {
  const threeC = spec.mechanics?.threeC || {};
  const coreLoop = spec.mechanics?.coreLoop || {};
  const waveDirector = spec.mechanics?.waveDirector || {};
  const weapons = Array.isArray(spec.tables?.weapons) ? spec.tables.weapons : [];
  const enemies = Array.isArray(spec.tables?.enemies) ? spec.tables.enemies : [];
  const upgrades = Array.isArray(spec.tables?.upgrades)
    ? spec.tables.upgrades
    : Array.isArray(spec.mechanics?.economy?.upgrades)
      ? spec.mechanics.economy.upgrades
      : [];

  const playerSpeed = pickNum(threeC.playerSpeedMps, threeC.playerSpeed, threeC.moveSpeed);
  const playerRadius = pickNum(threeC.playerRadiusM, threeC.playerRadius, threeC.radius);
  const playerHp = pickNum(threeC.playerHp, threeC.maxHp, threeC.hp);
  const arenaSpan = pickNum(
    coreLoop.arenaSpanM,
    coreLoop.arenaSpan,
    spec.levels?.[0]?.arenaSpanM,
    spec.levels?.[0]?.sizeM,
  );
  const waveDurationSec = pickNum(coreLoop.waveDurationSec, waveDirector.waveDurationSec);

  const primaryWeapon = weapons[0] || null;
  let weaponEffectiveDps = null;
  if (primaryWeapon) {
    const explicitDps = pickNum(primaryWeapon.effectiveDps, primaryWeapon.dps);
    if (isPosFinite(explicitDps)) {
      weaponEffectiveDps = explicitDps;
    } else {
      const dmg = pickNum(primaryWeapon.damage, primaryWeapon.dmg);
      const proj = pickNum(primaryWeapon.projectiles, 1) || 1;
      const cd = pickNum(primaryWeapon.cooldownSec, primaryWeapon.attackIntervalSec)
        ?? (isPosFinite(primaryWeapon.fireRateHz) ? 1 / primaryWeapon.fireRateHz : null);
      if (isPosFinite(dmg) && isPosFinite(cd)) {
        weaponEffectiveDps = (dmg * proj) / cd;
      }
    }
  }

  const gruntEnemy = enemies.find((e) => e?.role === 'grunt') || enemies[0] || null;
  const gruntHp = gruntEnemy ? pickNum(gruntEnemy.hp, gruntEnemy.maxHp) : null;
  const gruntHitDamage = gruntEnemy
    ? pickNum(gruntEnemy.hitDamage, gruntEnemy.damage, gruntEnemy.contactDamage, gruntEnemy.attackDamage)
    : null;

  const hasCamera = Boolean(
    threeC.camera ||
    isPosFinite(pickNum(threeC.cameraDistanceM, threeC.fovDeg, threeC.orthoHeightM)),
  );

  const missingCoreFields = [];
  if (!isPosFinite(playerSpeed)) missingCoreFields.push('mechanics.threeC.playerSpeed (m/s)');
  if (!isPosFinite(playerRadius)) missingCoreFields.push('mechanics.threeC.playerRadius (m)');
  if (!isPosFinite(playerHp)) missingCoreFields.push('mechanics.threeC.playerHp');
  if (!hasCamera) missingCoreFields.push('mechanics.threeC.camera (or status: "hgame-fallback" with defaults)');
  if (!isPosFinite(arenaSpan)) missingCoreFields.push('mechanics.coreLoop.arenaSpanM (m)');
  if (!isPosFinite(waveDurationSec)) missingCoreFields.push('mechanics.coreLoop.waveDurationSec (s)');
  if (!isPosFinite(weaponEffectiveDps)) missingCoreFields.push('tables.weapons[0] (damage + cooldownSec or effectiveDps)');
  if (!isPosFinite(gruntHp)) missingCoreFields.push('tables.enemies[0].hp');
  if (!isPosFinite(gruntHitDamage)) missingCoreFields.push('tables.enemies[0].hitDamage');

  return {
    threeC,
    coreLoop,
    waveDirector,
    weapons,
    enemies,
    upgrades,
    playerSpeed,
    playerRadius,
    playerHp,
    arenaSpan,
    waveDurationSec,
    weaponEffectiveDps,
    gruntHp,
    gruntHitDamage,
    missingCoreFields,
  };
}

function evaluateRatio(key, label, formula, value, min, max, suspectedFields, failHint) {
  if (!Number.isFinite(value)) {
    return {
      key,
      label,
      formula,
      value: null,
      min,
      max,
      pass: false,
      suspectedFields,
      diagnosis: `无法计算 ${label}：缺少有效的正数输入 (${suspectedFields.join(', ')})`,
    };
  }
  const rounded = Number(value.toFixed(4));
  const pass = value >= min && value <= max;
  return {
    key,
    label,
    formula,
    value: rounded,
    min,
    max,
    pass,
    suspectedFields: pass ? [] : suspectedFields,
    diagnosis: pass ? 'OK' : `${label}=${rounded} 超出合法区间 [${min}, ${max}]；疑似未换算字段: ${suspectedFields.join(', ')} (${failHint})`,
  };
}

function evaluateRatios(core) {
  const relSpeed = isPosFinite(core.playerSpeed) && isPosFinite(core.playerRadius)
    ? core.playerSpeed / (core.playerRadius * 2)
    : NaN;
  const traversal = isPosFinite(core.arenaSpan) && isPosFinite(core.playerSpeed)
    ? core.arenaSpan / core.playerSpeed
    : NaN;
  const gruntTtk = isPosFinite(core.gruntHp) && isPosFinite(core.weaponEffectiveDps)
    ? core.gruntHp / core.weaponEffectiveDps
    : NaN;
  const playerTtd = isPosFinite(core.playerHp) && isPosFinite(core.gruntHitDamage)
    ? core.playerHp / core.gruntHitDamage
    : NaN;

  return {
    relativeSpeedRatio: evaluateRatio(
      'relativeSpeedRatio',
      '相对移速比',
      'playerSpeed / (playerRadius * 2)',
      relSpeed,
      2.5,
      15,
      ['mechanics.threeC.playerSpeed', 'mechanics.threeC.playerRadius'],
      '常见于把像素移速 300px/s 直接当成 300m/s 导致角色飞出地图',
    ),
    arenaTraversalSec: evaluateRatio(
      'arenaTraversalSec',
      '场地横穿耗时(s)',
      'arenaSpan / playerSpeed',
      traversal,
      6,
      40,
      ['mechanics.coreLoop.arenaSpanM', 'mechanics.threeC.playerSpeed'],
      '场地尺寸与玩家移速单位不匹配，正常应 6s~40s 走完场地跨度',
    ),
    gruntTtkSec: evaluateRatio(
      'gruntTtkSec',
      '普通怪单杀耗时 TTK(s)',
      'gruntHp / weaponEffectiveDps',
      gruntTtk,
      0.1,
      5.0,
      ['tables.enemies[0].hp', 'tables.weapons[0].damage', 'tables.weapons[0].cooldownSec'],
      '疑似帧冷却未乘 tickHz 转秒，或武器伤害/怪物血量量纲失真',
    ),
    playerTtdHits: evaluateRatio(
      'playerTtdHits',
      '玩家生存容错 TTD(受击次数)',
      'playerHp / gruntHitDamage',
      playerTtd,
      3,
      25,
      ['mechanics.threeC.playerHp', 'tables.enemies[0].hitDamage'],
      '玩家血量与小怪单次伤害比例失衡，容易导致 0.5s 暴毙或刮痧无伤',
    ),
  };
}

function evaluateMvpSlice(spec, core) {
  const warnings = [];
  const charCount = Array.isArray(spec.tables?.characters)
    ? spec.tables.characters.length
    : (spec.mechanics?.threeC ? 1 : 0);
  const camCount = Array.isArray(spec.tables?.cameras)
    ? spec.tables.cameras.length
    : (spec.mechanics?.threeC?.camera ? 1 : 0);
  const weaponCount = core.weapons.length;
  const enemyCount = core.enemies.length;
  const waveCount = Array.isArray(spec.tables?.waves)
    ? spec.tables.waves.length
    : (Array.isArray(core.waveDirector?.waves) ? core.waveDirector.waves.length : (isPosFinite(core.waveDurationSec) ? 1 : 0));
  const upgradeCount = core.upgrades.length;

  let deductions = 0;
  if (charCount !== 1) {
    deductions += 5;
    warnings.push(`MVP 切片角色参数应收敛为 1 套（当前 ${charCount} 套），请先裁剪多余角色`);
  }
  if (camCount !== 1) {
    deductions += 5;
    warnings.push(`MVP 切片相机参数应收敛为 1 套（当前 ${camCount} 套）`);
  }
  if (weaponCount < 1 || weaponCount > 2) {
    deductions += 5;
    warnings.push(
      weaponCount > 2
        ? `MVP 切片超标：武器数量 ${weaponCount} 把（初版仅允许 1~2 把核心武器），请先裁剪至 1-1-2-1 切片跑通手感`
        : 'MVP 切片至少需要 1 把核心武器（1~2 把）',
    );
  }
  if (enemyCount < 2 || enemyCount > 3) {
    deductions += 5;
    warnings.push(
      enemyCount > 3
        ? `MVP 切片超标：敌人种类 ${enemyCount} 种（初版仅允许 2~3 种代表敌人），请先裁剪至 1-1-2-1 切片跑通手感`
        : `MVP 切片至少需要 2 种代表敌人（2~3 种，当前 ${enemyCount} 种）`,
    );
  }
  if (waveCount !== 1 || (isPosFinite(core.waveDurationSec) && (core.waveDurationSec < 30 || core.waveDurationSec > 90))) {
    deductions += 5;
    warnings.push(`MVP 切片只允许 1 套 ~60s 基础波次（当前波次数 ${waveCount}，时长 ${core.waveDurationSec ?? 'N/A'}s）`);
  }
  if (upgradeCount > 5) {
    deductions += 5;
    warnings.push(`MVP 切片超标：核心升级项 ${upgradeCount} 个（初版上限 5 个），请先做减法后再扩充`);
  }

  return {
    ok: warnings.length === 0,
    score: Math.max(0, 15 - deductions),
    counts: {
      characters: charCount,
      cameras: camCount,
      weapons: weaponCount,
      enemies: enemyCount,
      waves: waveCount,
      waveDurationSec: core.waveDurationSec,
      upgrades: upgradeCount,
    },
    warnings,
  };
}

/**
 * Evaluates a clean-spec payload against the compliance firewall, 1-1-2-1 MVP scope gate,
 * SI unit normalization, zero-unknown rule, and 4 dimensionless gameplay ratios.
 * @param {object} spec
 */
export function evaluateCleanSpec(spec) {
  const complianceViolations = [];
  if (!spec || typeof spec !== 'object') throw new Error('Spec must be a JSON object');
  if (spec.schemaVersion !== 1) complianceViolations.push('schemaVersion must equal 1');
  if (spec.specKind !== 'hgame-clean-spec') complianceViolations.push('specKind must equal "hgame-clean-spec"');
  if (!/^[A-Za-z0-9][A-Za-z0-9_-]{0,79}$/.test(String(spec.slug || ''))) {
    complianceViolations.push('slug must be an ASCII identifier');
  }
  const profile = spec.engineRecipe?.profile || spec.recommendedProfile;
  if (!['2d', '3d', 'ui'].includes(profile)) {
    complianceViolations.push('engineRecipe.profile must be 2d, 3d, or ui');
  }
  scanCompliance(spec, 'spec', complianceViolations);

  const mappedFallbacks = (spec.hgameFallbackModules || []).map((mod) => ({
    module: mod,
    hgameTarget: FALLBACK_MODULE_MAP[mod] || 'native HGame runtime subsystem',
  }));

  const { unitViolations, unitScore } = validateUnitSystem(spec);

  const unknownViolations = [];
  scanUnknownOrNull(spec.unitConversions, 'spec.unitConversions', unknownViolations);
  scanUnknownOrNull(spec.mechanics?.threeC, 'spec.mechanics.threeC', unknownViolations);
  scanUnknownOrNull(spec.mechanics?.coreLoop, 'spec.mechanics.coreLoop', unknownViolations);
  scanUnknownOrNull(spec.mechanics?.waveDirector, 'spec.mechanics.waveDirector', unknownViolations);
  scanUnknownOrNull(spec.tables?.weapons, 'spec.tables.weapons', unknownViolations);
  scanUnknownOrNull(spec.tables?.enemies, 'spec.tables.enemies', unknownViolations);

  const core = extractCoreAndTriangle(spec);
  const ratios = evaluateRatios(core);
  const ratiosAllGreen = Object.values(ratios).every((r) => r.pass);
  const ratiosScore = Object.values(ratios).reduce((acc, r) => acc + (r.pass ? 10 : 0), 0);

  const mvpSlice = evaluateMvpSlice(spec, core);

  let completenessScore = 0;
  if (unknownViolations.length === 0) completenessScore += 15;
  if (core.missingCoreFields.length === 0) completenessScore += 10;

  const rawScore = unitScore + completenessScore + ratiosScore + mvpSlice.score;
  const score = complianceViolations.length > 0 ? 0 : rawScore;

  const blockers = [
    ...complianceViolations,
    ...unitViolations,
    ...unknownViolations,
    ...core.missingCoreFields.map((f) => `missing core field: ${f}`),
    ...Object.values(ratios).filter((r) => !r.pass).map((r) => r.diagnosis),
    ...mvpSlice.warnings,
  ];

  const graduated =
    complianceViolations.length === 0 &&
    unitViolations.length === 0 &&
    unknownViolations.length === 0 &&
    core.missingCoreFields.length === 0 &&
    ratiosAllGreen &&
    mvpSlice.ok &&
    score >= GRADUATION_SCORE_MIN;

  const verdict = graduated
    ? '逆向提取已达毕业线，无需继续深挖原版，准许进入原型构建'
    : '未达毕业门禁，禁止进入生成阶段；请先修正单位换算/补齐 fallback 并收敛至 1-1-2-1 最小切片';

  return {
    valid: complianceViolations.length === 0,
    graduated,
    score,
    maxScore: 100,
    passingScore: GRADUATION_SCORE_MIN,
    profile,
    unitSystem: spec.unitSystem || null,
    complianceViolations,
    unitViolations,
    unknownViolations,
    missingCoreFields: core.missingCoreFields,
    ratiosAllGreen,
    ratios,
    mvpSlice,
    blockers,
    violations: blockers,
    mappedFallbacks,
    verdict,
    breakdown: {
      unitSystemAndConversions: `${unitScore}/20`,
      coreCompletenessAndZeroUnknown: `${completenessScore}/25`,
      dimensionlessRatios: `${ratiosScore}/40`,
      mvpSliceDiscipline: `${mvpSlice.score}/15`,
    },
  };
}

function formatReadinessReport(slug, evalRes) {
  const lines = [
    `=== HGame RE Readiness Report (${slug || 'unknown'}) ===`,
    `Score: ${evalRes.score}/${evalRes.maxScore} (Graduation >= ${evalRes.passingScore})  |  Status: ${evalRes.graduated ? 'GRADUATED [PASS]' : 'BLOCKED [FAIL]'}`,
    `Breakdown: Units=${evalRes.breakdown.unitSystemAndConversions}, Completeness=${evalRes.breakdown.coreCompletenessAndZeroUnknown}, Ratios=${evalRes.breakdown.dimensionlessRatios}, MVP-Slice=${evalRes.breakdown.mvpSliceDiscipline}`,
    '--- 4 Golden Dimensionless Ratios ---',
  ];
  for (const r of Object.values(evalRes.ratios)) {
    const tag = r.pass ? '[GREEN]' : '[RED]  ';
    lines.push(`  ${tag} ${r.label} (${r.formula}) = ${r.value ?? 'N/A'}  (range: ${r.min} ~ ${r.max})`);
    if (!r.pass) lines.push(`          -> ${r.diagnosis}`);
  }
  const c = evalRes.mvpSlice.counts;
  lines.push(`--- 1-1-2-1 MVP Slice Scope (${evalRes.mvpSlice.ok ? 'PASS' : 'WARN'}) ---`);
  lines.push(`  Chars=${c.characters}/1, Cameras=${c.cameras}/1, Weapons=${c.weapons}/1-2, Enemies=${c.enemies}/2-3, Waves=${c.waves}/1 (${c.waveDurationSec ?? 'N/A'}s), Upgrades=${c.upgrades}/<=5`);
  if (evalRes.blockers.length > 0) {
    lines.push('--- Blockers & Warnings ---');
    for (const b of evalRes.blockers) lines.push(`  * ${b}`);
  }
  lines.push(`Verdict: ${evalRes.verdict}`);
  return lines.join('\n');
}

function scaffoldProject(spec, targetDir) {
  const recipe = spec.engineRecipe || { profile: spec.recommendedProfile || '2d' };
  const args = [createGameScript, targetDir, '--profile', recipe.profile, '--bare', '--with', 'audio,save', '--name', spec.slug];
  if (recipe.renderer) args.push('--renderer', recipe.renderer);
  if (recipe.physics && recipe.physics !== 'none') args.push('--physics', recipe.physics);
  if (recipe.profile === '3d') args.push('--quality', 'auto');
  const res = spawnSync(process.execPath, args, { encoding: 'utf8' });
  if (res.error || res.status !== 0) {
    throw new Error(`create-game.mjs failed: ${res.stderr || res.error?.message || res.stdout}`);
  }
}

async function wireDoctorHelper(dest) {
  const simDir = path.join(dest, 'src', 'sim');
  await mkdir(simDir, { recursive: true });
  await writeFile(path.join(simDir, 'doctor.js'), DOCTOR_HELPER_TEMPLATE, 'utf8');
  const mainPath = path.join(dest, 'src', 'main.js');
  try {
    const mainSrc = await readFile(mainPath, 'utf8');
    if (!mainSrc.includes('./sim/doctor.js')) {
      await writeFile(mainPath, `import './sim/doctor.js';\n${mainSrc}`, 'utf8');
    }
  } catch {
    // Optional if custom main.js layout
  }
}

/** Copies only browser-safe runtime media/JSON from assetsFromDir into destAssetsDir. */
async function syncCuratedAssets(assetsFromDir, destAssetsDir) {
  const sourceRoot = path.resolve(assetsFromDir);
  const summary = { sourceRoot, destDir: destAssetsDir, copied: 0, skipped: 0 };

  async function walk(dir, relBase) {
    const entries = await readdir(dir, { withFileTypes: true });
    for (const entry of entries) {
      if (IGNORED_ASSET_DIRS.has(entry.name)) continue;
      const srcPath = path.join(dir, entry.name);
      const relPath = relBase ? path.join(relBase, entry.name) : entry.name;
      if (entry.isDirectory()) {
        await walk(srcPath, relPath);
        continue;
      }
      if (!entry.isFile()) continue;
      const ext = path.extname(entry.name).toLowerCase();
      if (!SAFE_RUNTIME_ASSET_EXTS.has(ext)) {
        summary.skipped++;
        continue;
      }
      const dstPath = path.join(destAssetsDir, relPath);
      await mkdir(path.dirname(dstPath), { recursive: true });
      await cp(srcPath, dstPath, { force: true });
      summary.copied++;
    }
  }

  await walk(sourceRoot, '');
  return summary;
}

async function main() {
  const opts = parseArgs(process.argv.slice(2));
  if (opts.help) {
    console.log('Usage: node validate-spec.mjs <clean-spec.json> [--eval] [--scaffold <project-dir>] [--assets-from <dir>] [--json] | --demo');
    return;
  }

  const spec = opts.demo ? DEMO_SPEC : JSON.parse(await readFile(path.resolve(opts.specPath), 'utf8'));
  const evalRes = evaluateCleanSpec(spec);

  const canPass = opts.allowDraft ? evalRes.valid : evalRes.graduated;
  if (!canPass) {
    const fail = {
      ok: false,
      graduated: evalRes.graduated,
      score: evalRes.score,
      maxScore: evalRes.maxScore,
      slug: spec.slug || null,
      verdict: evalRes.verdict,
      ratios: evalRes.ratios,
      mvpSlice: evalRes.mvpSlice,
      violations: evalRes.blockers,
    };
    if (opts.json) {
      console.error(JSON.stringify(fail, null, 2));
    } else {
      console.error(formatReadinessReport(spec.slug, evalRes));
      console.error(JSON.stringify(fail, null, 2));
    }
    process.exitCode = 1;
    return;
  }

  let importedAssets = null;
  if (opts.scaffold && !opts.demo) {
    const dest = path.resolve(opts.scaffold);
    scaffoldProject(spec, dest);
    const simDir = path.join(dest, 'src', 'sim');
    await mkdir(simDir, { recursive: true });
    await writeFile(path.join(simDir, 'spec.json'), JSON.stringify(spec, null, 2) + '\n', 'utf8');
    await wireDoctorHelper(dest);
    if (opts.assetsFrom) {
      importedAssets = await syncCuratedAssets(opts.assetsFrom, path.join(dest, 'assets'));
    }
  }

  const out = {
    ok: true,
    mode: opts.demo ? 'demo' : opts.evalMode ? 'eval' : 'spec',
    slug: spec.slug,
    profile: evalRes.profile,
    graduated: evalRes.graduated,
    score: evalRes.score,
    maxScore: evalRes.maxScore,
    breakdown: evalRes.breakdown,
    ratios: evalRes.ratios,
    mvpSlice: evalRes.mvpSlice,
    verdict: evalRes.verdict,
    mappedFallbacks: evalRes.mappedFallbacks,
    scaffoldedTo: opts.scaffold && !opts.demo ? path.resolve(opts.scaffold) : null,
    importedAssets,
  };
  if (opts.json) {
    console.log(JSON.stringify(out, null, 2));
  } else {
    console.log(formatReadinessReport(spec.slug, evalRes));
    if (out.scaffoldedTo) {
      console.log(`\nScaffolded to: ${out.scaffoldedTo} (with src/sim/spec.json & src/sim/doctor.js)`);
      if (importedAssets) {
        console.log(`Imported assets: ${importedAssets.copied} safe files copied (${importedAssets.skipped} non-runtime files skipped) -> ${importedAssets.destDir}`);
      }
    }
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  main().catch((err) => {
    console.error('validate-spec failed: ' + err.message);
    process.exitCode = 1;
  });
}
